const TITLES_ZH = ["林中的小枞树", "他向往的荣光", "最光辉的一夜", "被遗忘在阁楼", "一切都过去了"];
const chapters = draft.chapters.map((ch, ci) => {
  const gCh = G[ci], cnCh = CN[ci];
  if (ch.paragraphs.length !== gCh.length) throw new Error(`章${ci+1} 段数 ${ch.paragraphs.length} != G ${gCh.length}`);
  if (gCh.length !== cnCh.length) throw new Error(`章${ci+1} G段数 != CN段数`);
  const paragraphs = ch.paragraphs.map((para, pi) => {
    const groups = gCh[pi], cns = cnCh[pi];
    if (groups.length !== cns.length) throw new Error(`章${ci+1}段${pi} 分组${groups.length} != 译文${cns.length}`);
    return groups.map((sis, gi) => {
      const en = sis.map((si) => {
        if (!para[si]) throw new Error(`章${ci+1}段${pi} si=${si} 越界(段长${para.length})`);
        return para[si].en;
      }).join(" ");
      return { en, cn: cns[gi] };
    });
  });
  return { idx: ch.idx, title_en: ch.title_en, title_zh: TITLES_ZH[ci], paragraphs };
});

