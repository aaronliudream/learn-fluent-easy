/** Sight Words 教学组(Fry's 4 组) */
export type SightWordGroup = {
  id: string;              // "sg1" ~ "sg4"
  groupName: string;       // "第 1 组 · 最常见的词"
  groupNameEn: string;     // "Group 1 — Top 25 Most Common"
  rangeLabel: string;      // "Fry's 1-25"
  sparkIntro: string;      // 进入这组时 Spark 说的话
  sparkOutro: string;      // 完成这组时 Spark 说的话
  unlockReq: string;
  sortOrder: number;
};

/** 单个 Sight Word */
export type SightWordItem = {
  id: string;              // "sw_the"
  groupId: string;         // "sg1"
  rank: number;            // Fry's 排名 1-100
  word: string;            // "the"
  ipa: string;             // 音标 "/ðə/"
  meaningCn: string;       // 中文意思(功能性,孩子能懂)
  pos: string;             // 词性 "art./pron./conj./prep./n./v./adj./adv."
  posCn: string;           // 词性中文 "冠词" "代词" "连词" ...
  exampleSentence: string; // 简单例句
  exampleSentenceCn: string;
  exampleSentenceEmoji?: string; // 句子配图 emoji 串
  difficulty: 1 | 2 | 3 | 4; // 难度:1=最易,4=最难
  sparkLine?: string;      // 可选 Spark 叙事(关键词才有)
  sortOrder: number;       // 在组内的展示顺序
};

