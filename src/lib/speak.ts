// Synchronously start playback inside the user-gesture click handler so
// mobile browsers (especially iOS Safari) don't block the eventual audio.
// We immediately call play() on a real <audio> with a short silent clip;
// once the network fetch resolves we just swap the src on the SAME element
// and call play() again — the gesture has already been "consumed" by the
// first play(), so the second call works without a fresh user tap.
export const unlockAudioSync = (): HTMLAudioElement | null => {
  const audio = getSharedAudio();
  if (!audio) return null;
  try {
    audio.muted = false;
    audio.volume = 1;
    audio.src = SILENT_WAV;
    audio.load();
    const p = audio.play();
    if (p && typeof p.catch === "function") p.catch(() => {});
    // Route through GainNode for loudness boost. Must run inside the
    // user-gesture window so the AudioContext can start unsuspended.
    ensureLoudnessRouting(audio);
  } catch {}
  return audio;
};

// ---------- Browser TTS fallback ----------
const VOICE_PREFS: Record<string, string[]> = {
  alloy: ["Samantha", "Google US English", "Microsoft Aria", "Ava"],
  shimmer: ["Allison", "Ava", "Samantha", "Microsoft Aria"],
  nova: ["Ava", "Jenny", "Aria", "Samantha"],
  echo: ["Alex", "Daniel", "Microsoft Guy", "Google UK English Male"],
  onyx: ["Daniel", "Alex", "Microsoft David", "Google US English Male"],
  fable: ["Oliver", "Daniel", "Google UK English", "Microsoft Ryan"],
};

const waitForVoices = (): Promise<SpeechSynthesisVoice[]> => {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return Promise.resolve([]);
  const ready = speechSynthesis.getVoices();
  if (ready.length > 0) return Promise.resolve(ready);
  return new Promise((resolve) => {
    const done = () => resolve(speechSynthesis.getVoices());
    speechSynthesis.onvoiceschanged = done;
    window.setTimeout(done, 600);
  });
};

const pickBrowserVoice = (voices: SpeechSynthesisVoice[], voiceId: string) => {
  const prefs = VOICE_PREFS[voiceId] ?? VOICE_PREFS.alloy;
  return voices
    .filter((v) => v.lang.toLowerCase().startsWith("en"))
    .map((v) => {
      const name = v.name.toLowerCase();
      let score = 50;
      const idx = prefs.findIndex((p) => name.includes(p.toLowerCase()));
      if (idx >= 0) score += 120 - idx * 12;
      if (/(enhanced|premium|neural|natural)/.test(name)) score += 40;
      if (v.localService) score += 10;
      return { v, score };
    })
    .sort((a, b) => b.score - a.score)[0]?.v;
};

const speakBrowserFallback = async (text: string, voiceId: string, speed: number, token: number) => {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
  const voices = await waitForVoices();
  const voice = pickBrowserVoice(voices, voiceId);
  const rate = Math.min(1.0, Math.max(0.65, (Number(speed) || 0.85) * 0.9));
  await new Promise<void>((resolve) => {
    if (token !== speakToken) return resolve();
    const u = new SpeechSynthesisUtterance(text);
    if (voice) u.voice = voice;
    u.lang = voice?.lang || "en-US";
    u.rate = rate;
    u.pitch = voiceId === "onyx" || voiceId === "echo" ? 0.9 : 0.98;
    u.onend = () => resolve();
    u.onerror = () => resolve();
    speechSynthesis.speak(u);
  });
};

// ---------- TTS via edge function ----------
// Use a direct fetch (not supabase.functions.invoke) so we can read raw
// audio/mpeg responses without forcing JSON parsing. The cold path returns
// the MP3 bytes directly; the cache-hit path returns a JSON {audioUrl} so
// the browser can fetch from the CDN.
const SUPABASE_FN_URL = `${import.meta.env.VITE_SUPABASE_URL}/functions/v1/tts`;
const SUPABASE_ANON = import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY as string;

const fetchTTS = async (text: string, voiceId: string, speed: number, accent?: string): Promise<string | null> => {
  // Strip dialogue speaker labels before hashing + sending. Idempotent + no-op
  // for label-free text, so the content-addressed cache key is unchanged for
  // everything except dialogue transcripts (which now synthesize clean audio).
  text = cleanForTTS(text);
  const cacheKey = `${voiceId}|${speed}|${accent || ''}|${text}`;
  const cached = audioCache.get(cacheKey);
  if (cached) return cached;

  try {
    const session = (await supabase.auth.getSession()).data.session;
    const headers: Record<string, string> = {
      "Content-Type": "application/json",
      apikey: SUPABASE_ANON,
      Authorization: `Bearer ${session?.access_token || SUPABASE_ANON}`,
    };
    const res = await fetch(SUPABASE_FN_URL, {
      method: "POST",
      headers,
      body: JSON.stringify({ text, voiceId, speed, accent, format: "url" }),
    });
    if (!res.ok) {
      console.warn("[tts] edge function status:", res.status);
      return null;
    }
    // Edge function always responds with JSON containing a CDN URL.
    // (Previously it could return raw audio/mpeg bytes on cold path; that
    // bypassed the CDN and made first plays slow for mainland-China users.)
    let url: string | null = null;
    const ct = res.headers.get("content-type") || "";
    if (ct.includes("application/json")) {
      const data = await res.json();
      if (data?.audioUrl) {
        url = data.audioUrl as string;
      } else if (data?.audioContent) {
        // Legacy base64 envelope — kept for back-compat only.
        url = `data:${data.mimeType || "audio/mpeg"};base64,${data.audioContent}`;
      } else {
        console.warn("[tts] no audio returned");
        return null;
      }
    } else if (ct.startsWith("audio/")) {
      // Cold path: edge streams MP3 bytes but exposes the CDN URL in a header.
      // Prefer the CDN URL so playback + localStorage use the same hash as prefetch.
      const cdnHeader = res.headers.get("x-audio-url");
      if (cdnHeader?.startsWith("http")) {
        url = cdnHeader;
      } else {
        console.warn("[tts] edge function returned raw audio bytes — CDN bypassed. Redeploy the tts function.");
        const blob = await res.blob();
        url = URL.createObjectURL(blob);
      }
    } else {
      console.warn("[tts] unexpected content-type:", ct);
      return null;
    }
    if (audioCache.size >= MAX_CACHE) {
      const firstKey = audioCache.keys().next().value;
      if (firstKey) audioCache.delete(firstKey);
    }
    audioCache.set(cacheKey, url);
    // Persist CDN URLs (not blob: URLs — those die with the page).
    if (url.startsWith("http")) savePersist(cacheKey, url);
    return url;
  } catch (e) {
    console.warn("[tts] fetch failed:", e);
    return null;
  }
};

// 取或启动某 key 的冷合成,并对同 key 的并发调用【去重】(edge 只被打一次)。
// 返回解析为可播 URL / null 的共享 Promise;每个调用方各自决定拿到 URL 后怎么播。
// 这把旧的"去抖 return 丢弃点击"替换为"复用同一合成、各自在自己的手势上下文里播放"。
const coldFetchShared = (
  cacheKey: string,
  text: string,
  voiceId: string,
  speed: number,
  accent?: string,
): Promise<string | null> => {
  const existing = inflightCold.get(cacheKey);
  if (existing) return existing;
  const p = (async () => {
    try {
      return await fetchTTS(text, voiceId, speed, accent);
    } finally {
      // 仅当仍是本次合成时才清除,避免误删后来者。
      if (inflightCold.get(cacheKey) === p) inflightCold.delete(cacheKey);
    }
  })();
  inflightCold.set(cacheKey, p);
  return p;
};

// 是否处于真实用户手势(瞬时激活 transient activation)中。
// onClick 里同步调用 → true;useEffect / 定时器里的 mount 自动播 → false。
// 用途(修复2):非手势 + 冷缓存 的调用注定被 iOS autoplay 策略拦截,让它只走【纯网络预热】
// (灌缓存、不碰 <audio>、不改播放状态),把真正出声留给真实手势那一次点击,
// 从根源上避免"被拦截的自动播污染全局状态、进而害得下一次点击哑火"。
// 说明:iOS 上被拦截的 play() 常"resolve 但无声"而非 reject,故不能靠 play() 失败回调判断,
// 只能在调用前判活跃度。API 不可用(旧 Safari)时回退为 true → 维持既有行为,绝不比现状更差。
const hasUserGesture = (): boolean => {
  if (typeof navigator === "undefined") return true;
  const ua = (navigator as Navigator & { userActivation?: { isActive?: boolean } }).userActivation;
  if (!ua || typeof ua.isActive !== "boolean") return true;
  return ua.isActive;
};

const playUrlOn = (
  audio: HTMLAudioElement,
  url: string,
  token: number,
): Promise<boolean> =>
  new Promise((resolve) => {
    if (token !== speakToken) return resolve(false);
    try {
      audio.pause();
      audio.muted = false;
      audio.volume = 1;
      audio.src = url;
      audio.load();
    } catch {
      return resolve(false);
    }
    currentAudio = audio;
    audio.onended = () => resolve(true);
    audio.onerror = () => resolve(false);
    const p = audio.play();
    if (p && typeof p.catch === "function") {
      p.catch(() => resolve(false));
    }
  });

// Fallback when the shared (Web-Audio-routed) element fails — e.g.
// AudioContext suspended on mobile, or a stale CDN URL. A fresh element
// bypasses the GainNode graph and still plays inside the user gesture.
const playUrlDirect = (url: string, token: number): Promise<boolean> =>
  new Promise((resolve) => {
    if (token !== speakToken) return resolve(false);
    try {
      const audio = new Audio(url);
      audio.preload = "auto";
      audio.volume = 1;
      audio.setAttribute("playsinline", "true");
      currentAudio = audio;
      audio.onended = () => resolve(true);
      audio.onerror = () => resolve(false);
      const p = audio.play();
      if (p && typeof p.catch === "function") {
        p.catch(() => resolve(false));
      }
    } catch {
      resolve(false);
    }
  });

const playUrl = async (
  audio: HTMLAudioElement | null,
  url: string,
  token: number,
): Promise<boolean> => {
  if (audio) {
    const routed = await playUrlOn(audio, url, token);
    if (routed) return true;
  }
  return playUrlDirect(url, token);
};

// IMPORTANT: `speak()` must be called *synchronously* inside the click
// handler. We do the audio-element creation + first `.play()` BEFORE any
// `await`, so mobile browsers see this as a valid user-initiated playback.
// The async work continues afterwards and just updates the src.
/** Play a known-good MP3 URL (same mobile unlock path as `speak`). */
/**
 * 播一个**预生成的音频文件**（不经 TTS）。
 *
 * @returns `true` = 确实播出来了；`false` = 没播成（URL 404/网络失败/被更新的播放请求抢占）。
 *
 * ⚠️ 为什么返回布尔而不是抛错：这个函数有 6 个调用点，其中几处是 `void speakFromUrl(...)`
 * 或挂在 onClick 上，抛错会变成未捕获的 rejection。返回值是**让失败可感知**的最小改动，
 * 老调用方忽略返回值时行为不变。
 *
 * 在此之前它恒 resolve(void)：URL 死了也**静默无声、且调用方无从得知**——
 * 听力专区就是 `if (audio_url) speakFromUrl() else speak(transcript)` 的二选一，
 * 死链意味着彻底没声。现在调用方可以据此回落到 TTS。
 */
export const speakFromUrl = (url: string): Promise<boolean> => {
  if (typeof window === "undefined" || !url) return Promise.resolve(false);
  const resolved = url.startsWith("/") ? `${window.location.origin}${url}` : url;
  stopCurrent();
  const audio = unlockAudioSync();
  const myToken = speakToken;
  return (async () => {
    if (await playUrl(audio, resolved, myToken)) return true;
    return playUrlDirect(resolved, myToken);
  })();
};

export const speak = (text: string, opts?: { accent?: "UK" | "US" | "BOTH"; voiceId?: string; speed?: number }): Promise<void> => {
  if (!text) return Promise.resolve();
  const trimmed = text.trim();
  if (!trimmed) return Promise.resolve();
  const settings = loadSettings();
  const voiceId = opts?.voiceId || settings.voiceId;
  const speed = opts?.speed ?? settings.speed;
  const accent = opts?.accent;
  const cacheKey = `${voiceId}|${speed}|${accent || ''}|${trimmed}`;

  // 【修复2】非手势(useEffect / 定时器里的 mount 自动播)且缓存为冷 → 只做纯网络预热:
  //   复用/启动共享冷合成把音频灌进缓存,但不碰 <audio>、不 stopCurrent、不改任何播放状态。
  //   这样"注定被 iOS autoplay 拦截"的自动播不再污染全局状态,真正出声留给真实手势那次点击。
  //   缓存已热(warmUrl)的自动播照常走下面的播放路径 → 桌面/已解锁可自动出声,行为不变。
  const warmUrl = audioCache.get(cacheKey) ?? loadPersist().get(cacheKey);
  if (!warmUrl && !hasUserGesture()) {
    void coldFetchShared(cacheKey, trimmed, voiceId, speed, accent);
    return Promise.resolve();
  }

  lastSpoken = trimmed;
  stopCurrent();

  // 1) SYNC: grab/create the <audio> and start play() immediately. This
  //    keeps us inside the user-gesture window.
  const audio = unlockAudioSync();
  const myToken = speakToken;

  const useCachedUrl = (url: string): boolean => {
    if (isLegacyBadTtsKey(cacheKey) || !isValidOClockCacheEntry(cacheKey, url)) {
      audioCache.delete(cacheKey);
      loadPersist().delete(cacheKey);
      return false;
    }
    return true;
  };

  const finishPlayback = async (url: string): Promise<void> => {
    if (myToken !== speakToken) return;
    const played = await playUrl(audio, url, myToken);
    if (played) return;
    await speakBrowserFallback(trimmed, voiceId, speed, myToken);
  };

  const retryAfterBadUrl = async (invalidatePersist: boolean): Promise<void> => {
    if (myToken !== speakToken) return;
    audioCache.delete(cacheKey);
    if (invalidatePersist) loadPersist().delete(cacheKey);
    const url = await fetchTTS(trimmed, voiceId, speed, accent);
    if (url) await finishPlayback(url);
    else await speakBrowserFallback(trimmed, voiceId, speed, myToken);
  };

  // 2) Cache hit → swap src right away, no network wait.
  const cached = audioCache.get(cacheKey);
  if (cached) {
    if (useCachedUrl(cached)) {
      return (async () => {
        const played = await playUrl(audio, cached, myToken);
        if (played) return;
        await retryAfterBadUrl(false);
      })();
    }
    audioCache.delete(cacheKey);
  }

  // 2b) localStorage hit — survives page reloads.
  const persistedUrl = loadPersist().get(cacheKey);
  if (persistedUrl) {
    if (useCachedUrl(persistedUrl)) {
      audioCache.set(cacheKey, persistedUrl);
      return (async () => {
        const played = await playUrl(audio, persistedUrl, myToken);
        if (played) return;
        await retryAfterBadUrl(true);
      })();
    }
    loadPersist().delete(cacheKey);
  }

  // 3) Cache miss(冷)→【修复1】复用共享冷合成 Promise(同词并发只合成一次),
  //    拿到 URL 后用【本次调用的手势上下文】播放。去抖的正确语义是"等它合成好再播",
  //    不是"丢弃点击":用户点击本身即有效手势,await 后在同一个已被 unlockAudioSync 消费
  //    过手势的 <audio> 上换 src,iOS 会放行。若期间来了更新的播放/停止(speakToken 变了),
  //    本次结果由 finishPlayback / speakBrowserFallback 内的 token 校验丢弃 → 最新一次点击胜出。
  return (async () => {
    const url = await coldFetchShared(cacheKey, trimmed, voiceId, speed, accent);
    if (myToken !== speakToken) return;
    if (url) await finishPlayback(url);
    else await speakBrowserFallback(trimmed, voiceId, speed, myToken);
  })();
};

/** 某文本在该 voice/speed/accent 下是否正处于冷合成中(现基于去重表 inflightCold)。 */
export const isSynthInFlight = (text: string, voiceId: string, speed: number, accent?: string): boolean =>
  inflightCold.has(`${voiceId}|${speed}|${accent || ''}|${(text || '').trim()}`);

// Speak a list of sentences one-by-one with a small pause between them.
// This sounds far more natural than concatenating an entire paragraph and
// sending it to TTS as one long string (which OpenAI tends to read very
// fast and without breath pauses).
export const speakSequence = async (
  sentences: string[],
  opts: {
    gapMs?: number;
    onIndex?: (i: number) => void;
    accent?: "UK" | "US" | "BOTH";
    voiceId?: string;
    speed?: number;
  } = {},
): Promise<void> => {
  const gapMs = opts.gapMs ?? 80;
  const list = sentences.map((s) => (s || "").trim()).filter(Boolean);
  if (list.length === 0) return;
  const mySeq = ++sequenceId;
  // Prefetch the first item's audio so playback starts with no dead air.
  const settings = loadSettings();
  const voiceId = opts.voiceId ?? settings.voiceId;
  const speed = opts.speed ?? settings.speed;
  const accent = opts.accent;
  const prefetch = (text: string) => {
    // Cache key MUST mirror fetchTTS/speak exactly (`${voiceId}|${speed}|${accent||''}|${text}`),
    // else accented calls miss the cache the prefetch just warmed.
    const key = `${voiceId}|${speed}|${accent || ''}|${text}`;
    if (!audioCache.has(key)) {
      // fire-and-forget; result is stored in cache by fetchTTS
      void fetchTTS(text, voiceId, speed, accent);
    }
  };
  prefetch(list[0]);
  for (let i = 0; i < list.length; i++) {
    if (mySeq !== sequenceId) return; // a new sequence (or stop) started
    opts.onIndex?.(i);
    // Kick off prefetch of the NEXT sentence while we play the current one,
    // so the gap between sentences is just the configured gapMs (not network).
    if (i + 1 < list.length) prefetch(list[i + 1]);
    await speak(list[i], { voiceId, speed, accent });
    if (mySeq !== sequenceId) return;
    if (i < list.length - 1) {
      await new Promise((r) => setTimeout(r, gapMs));
    }
  }
  opts.onIndex?.(-1);
};

