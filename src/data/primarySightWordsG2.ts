/** 按组取所有 G2 Sight Words */
export function getSightWordsByGroupG2(groupId: string): SightWordItem[] {
  return SIGHT_WORD_ITEMS_G2.filter(w => w.groupId === groupId).sort((a, b) => a.sortOrder - b.sortOrder);
}

/** 按 Fry's 频率取所有 G2 词 */
export function getSightWordsByFryOrderG2(): SightWordItem[] {
  return [...SIGHT_WORD_ITEMS_G2].sort((a, b) => a.rank - b.rank);
}

/** 按词查找 G2 */
export function findSightWordG2(word: string): SightWordItem | undefined {
  const lower = word.toLowerCase();
  return SIGHT_WORD_ITEMS_G2.find(w => w.word.toLowerCase() === lower);
}

/** 取下一个未掌握的 G2 词 */
export function getNextSightWordG2(masteredIds: string[]): SightWordItem | null {
  const sorted = getSightWordsByFryOrderG2();
  return sorted.find(w => !masteredIds.includes(w.id)) || null;
}

