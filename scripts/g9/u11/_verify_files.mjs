import { readFileSync } from 'node:fs';
const D='scripts/g9/u11/'; const L='ABCD';
const load=n=>JSON.parse(readFileSync(D+`g9-u11-${n}.json`,'utf8'));
let ERR=[],WARN=[]; const e=m=>ERR.push(m),w=m=>WARN.push(m);
const allQids=new Set(); const dq=id=>{if(allQids.has(id))e(`重复qid ${id}`);allQids.add(id);};
const vo=load('vocab');
console.log(`vocab: ${vo.words.length} ${vo.volume==='9'?'':'❌vol'}`);
const vw=new Set(); vo.words.forEach(x=>{if(vw.has(x.word))e(`vocab重复 ${x.word}`);vw.add(x.word);});
if(JSON.stringify(vo.words.map(x=>x.freq_rank))!==JSON.stringify([...Array(vo.words.length)].map((_,i)=>i+1)))w('freq_rank非连续');
const gr=load('grammar');
console.log(`grammar: ${gr.points.length}点/${gr.questions.length}题 ${gr.points.length===3&&gr.questions.length===60?'✅':'❌'}`);
gr.points.forEach(p=>{if(p.category!=='verb')e(`point ${p.code} cat≠verb`);});
const dist={A:0,B:0,C:0,D:0};const catcnt={};
gr.questions.forEach(q=>{dq(q.qid);
  if(q.volume!=='9'||q.unit!=='U11')e(`${q.qid} vol/unit`);
  if(new Set(q.options).size!==4)e(`${q.qid} 选项重复 ${JSON.stringify(q.options)}`);
  if(q.options[q.answer_index]!==q.answer_text)e(`${q.qid} answer_text≠opts[idx]`);
  if(q.category!=='verb')e(`${q.qid} cat≠verb`);
  catcnt[q.category]=(catcnt[q.category]||0)+1; dist[L[q.answer_index]]++;});
console.log(`  ABCD: ${JSON.stringify(dist)} ${Object.values(dist).every(v=>v===15)?'✅各15':'⚠️'}`);
console.log(`  category: ${JSON.stringify(catcnt)} ${catcnt.verb===60&&Object.keys(catcnt).length===1?'✅全verb':'❌'}`);
const rd=load('reading');let rq=0;
rd.passages.forEach(p=>{if(p.volume!=='9')e(`${p.code} vol`);
  const vn=p.vocab_notes||[];if(vn.length!==3)e(`${p.code} vocab_notes≠3`);
  vn.forEach(x=>{if(!p.body.toLowerCase().includes(x.word.toLowerCase()))e(`${p.code} 生词不在课文 ${x.word}`);});
  if(p.questions.length!==5)e(`${p.code} 题≠5`);
  p.questions.forEach(q=>{rq++;dq(q.qid);if(new Set(q.options).size!==4)e(`${q.qid} 选项重复`);if(L[q.answer_index]!==q.answer)e(`${q.qid} answer≠idx`);});});
console.log(`reading: ${rd.passages.length}篇/${rq}题 ${rd.passages.length===6&&rq===30?'✅':'❌'}`);
const cl=load('cloze');let cq=0;
cl.passages.forEach(p=>{if(p.volume!=='9')e(`${p.code} vol`);
  const b=(p.body.match(/\(\d+\)____/g)||[]).length;if(b!==p.questions.length)e(`${p.code} 空${b}≠题${p.questions.length}`);
  if(p.questions.length!==10)e(`${p.code} 题≠10`);
  p.questions.forEach((q,i)=>{cq++;if(q.blank!==i+1)e(`${p.code} blank序`);if(new Set(q.options).size!==4)e(`${p.code}#${q.blank} 选项重复`);if(L[q.answer_index]!==q.answer)e(`${p.code}#${q.blank} answer≠idx`);});});
console.log(`cloze: ${cl.passages.length}篇/${cq}题 ${cl.passages.length===6&&cq===60?'✅':'❌'}`);
const li=load('listening');let lq=0;
li.exercises.forEach(x=>{if(x.volume!=='9')e(`${x.code} vol`);
  if(!x.translation_cn||!x.translation_cn.trim())e(`${x.code} 无tcn`);
  if(!['dialogue','passage'].includes(x.type))e(`${x.code} type非法 ${x.type}`);
  if((x.type==='dialogue')!==(x.kind==='long'))e(`${x.code} type/kind不匹配`);
  if(x.questions.length!==5)e(`${x.code} 题≠5`);
  x.questions.forEach(q=>{lq++;dq(q.qid);if(new Set(q.options).size!==4)e(`${q.qid} 选项重复`);if(q.options[q.answer_index]!==q.answer_text)e(`${q.qid} answer_text≠opts[idx]`);});});
console.log(`listening: ${li.exercises.length}篇/${lq}题 ${li.exercises.length===6&&lq===30?'✅':'❌'} kind:${li.exercises.map(x=>x.kind).join(',')}`);
const wr=load('writing').writing;
console.log(`writing: scoring=dict ${typeof wr.scoring==='object'&&!Array.isArray(wr.scoring)?'✅':'❌'}, vol ${wr.volume==='9'?'✅':'❌'}`);
console.log(`总qid: ${allQids.size} ${allQids.size===120?'✅':'❌'}`);
console.log(`===ERR(${ERR.length})===`);ERR.forEach(m=>console.log(' ❌ '+m));
console.log(`===WARN(${WARN.length})===`);WARN.forEach(m=>console.log(' ⚠️ '+m));
console.log(ERR.length===0?'✅ 无ERROR':'❌ 有ERROR');
