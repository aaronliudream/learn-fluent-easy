/** 按组取所有 Sight Words(按 Fry's 频率顺序) */
export function getSightWordsByGroup(groupId: string): SightWordItem[] {
  return SIGHT_WORD_ITEMS.filter(w => w.groupId === groupId).sort((a, b) => a.sortOrder - b.sortOrder);
}

/** 按 Fry's 频率取所有 100 个 */
export function getSightWordsByFryOrder(): SightWordItem[] {
  return [...SIGHT_WORD_ITEMS].sort((a, b) => a.rank - b.rank);
}

/** 按词查找(支持大小写) */
export function findSightWord(word: string): SightWordItem | undefined {
  const lower = word.toLowerCase();
  return SIGHT_WORD_ITEMS.find(w => w.word.toLowerCase() === lower);
}

/** 按难度筛选(1=最易,4=最难) */
export function getSightWordsByDifficulty(difficulty: 1 | 2 | 3 | 4): SightWordItem[] {
  return SIGHT_WORD_ITEMS.filter(w => w.difficulty === difficulty);
}

/** 取某组的词数 */
export function getWordsInGroup(groupId: string): number {
  return SIGHT_WORD_ITEMS.filter(w => w.groupId === groupId).length;
}

/** 取所有已解锁的词(根据用户完成到第几组) */
export function getUnlockedSightWords(completedGroupIds: string[]): SightWordItem[] {
  if (completedGroupIds.length === 0) {
    return getSightWordsByGroup("sg1");
  }
  const groupOrder = SIGHT_WORD_GROUPS.map(g => g.id);
  const highestCompletedIdx = Math.max(...completedGroupIds.map(g => groupOrder.indexOf(g)));
  const accessibleGroups = groupOrder.slice(0, highestCompletedIdx + 2);
  return SIGHT_WORD_ITEMS.filter(w => accessibleGroups.includes(w.groupId));
}

