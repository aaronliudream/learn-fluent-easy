-- ════════════════════════════════════════════════════════════════════════
-- 资料下载区:私有桶 downloads + 3 张表(categories/subjects/items)+ RLS。
-- 纯新增,不动任何现有表/桶/策略。幂等(可重复跑)。
-- 桶约定(权限按文件夹前缀):
--   · previews/*  → 任何人(含游客)可生成签名URL(有限预览,故预览文件必须放 previews/ 下)
--   · 其余任意路径 → 仅登录用户可生成签名URL(完整下载,file_path 可放桶内任意位置)
--   两者都只走时效签名URL,桶私有、无公开直链。
-- ════════════════════════════════════════════════════════════════════════
begin;

-- ── 1) 私有桶 ──────────────────────────────────────────────────────────
insert into storage.buckets (id, name, public)
values ('downloads', 'downloads', false)
on conflict (id) do nothing;

drop policy if exists "downloads previews readable by all"        on storage.objects;
drop policy if exists "downloads files readable by authenticated" on storage.objects;

-- 游客只能读 previews/ 下的预览文件
create policy "downloads previews readable by all"
  on storage.objects for select
  using ( bucket_id = 'downloads' and (storage.foldername(name))[1] = 'previews' );

-- 登录用户可读整桶任意文件(完整下载,file_path 不限文件夹)
create policy "downloads files readable by authenticated"
  on storage.objects for select
  to authenticated
  using ( bucket_id = 'downloads' );

-- ── 2) 学段大类 ────────────────────────────────────────────────────────
create table if not exists public.downloads_categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  sort_order  int  not null default 0,
  created_at  timestamptz not null default now()
);

-- ── 3) 大类下细分(主要给成人考试:四六级/托福/雅思/考研/以后 GRE…)──────
create table if not exists public.downloads_subjects (
  id          bigint generated by default as identity primary key,
  category_id bigint not null references public.downloads_categories(id) on delete cascade,
  name        text not null,
  sort_order  int  not null default 0,
  created_at  timestamptz not null default now()
);

-- ── 4) 资料 ────────────────────────────────────────────────────────────
create table if not exists public.downloads_items (
  id            bigint generated by default as identity primary key,
  title         text   not null,
  description   text,
  file_type     text   not null default 'pdf',          -- pdf/docx/…
  file_path     text   not null,                         -- 桶内完整文件路径,如 files/xxx.pdf
  category_id   bigint not null references public.downloads_categories(id) on delete cascade,
  subject_id    bigint references public.downloads_subjects(id) on delete set null,
  material_type text   not null default '其他',          -- 真题/讲义/词汇/练习/听力/范文/其他
  preview_path  text,                                    -- 桶内预览路径,如 previews/xxx.pdf(可空)
  sort_order    int    not null default 0,
  is_published  boolean not null default true,
  created_at    timestamptz not null default now()
);

create index if not exists downloads_items_category_idx    on public.downloads_items(category_id);
create index if not exists downloads_items_subject_idx     on public.downloads_items(subject_id);
create index if not exists downloads_subjects_category_idx on public.downloads_subjects(category_id);

-- ── RLS:三张表对外只读(写仅 service role/后台);items 仅 published 可见 ──
alter table public.downloads_categories enable row level security;
alter table public.downloads_subjects   enable row level security;
alter table public.downloads_items       enable row level security;

drop policy if exists "downloads_categories readable by all"        on public.downloads_categories;
drop policy if exists "downloads_subjects readable by all"          on public.downloads_subjects;
drop policy if exists "downloads_items published readable by all"   on public.downloads_items;

create policy "downloads_categories readable by all"
  on public.downloads_categories for select using (true);
create policy "downloads_subjects readable by all"
  on public.downloads_subjects for select using (true);
create policy "downloads_items published readable by all"
  on public.downloads_items for select using (is_published = true);

-- ── 预置 4 个学段大类(幂等:按 name 去重)────────────────────────────────
insert into public.downloads_categories (name, sort_order)
select v.name, v.sort_order
from (values
  ('小学英语', 1),
  ('初中英语', 2),
  ('高中英语', 3),
  ('成人·考试英语', 4)
) as v(name, sort_order)
where not exists (
  select 1 from public.downloads_categories c where c.name = v.name
);

commit;

-- 校验
select 'categories' as t, count(*) from public.downloads_categories
union all select 'subjects', count(*) from public.downloads_subjects
union all select 'items', count(*) from public.downloads_items;
