// ---------- Predictive CDN URL (skips Edge Function on cache hit) ----------
// The `tts` Edge Function uses a content-addressed cache: the same
// (provider, voice, speed, accent, text) tuple always lands at the same
// path on the public CDN bucket. We replicate that hashing here so the
// browser can guess the URL and try it directly — saving the Edge
// Function round-trip when the audio was already generated by anyone
// before. On a CDN miss (HEAD 404) we fall back to the Edge Function.
const SUPABASE_URL = import.meta.env.VITE_SUPABASE_URL as string;
const AUDIO_CDN_BASE = (import.meta.env.VITE_AUDIO_CDN_BASE as string | undefined)?.replace(/\/$/, "");
const TTS_BUCKET = "tts-audio";

function buildCdnUrl(path: string): string {
  if (AUDIO_CDN_BASE) return `${AUDIO_CDN_BASE}/${path}`;
  return `${SUPABASE_URL}/storage/v1/object/public/${TTS_BUCKET}/${path}`;
}

// localStorage cache of (key -> CDN URL) for known-good URLs. Survives
// page reloads, so repeat phrases are instant across sessions.
const PERSIST_KEY = "tts.urls.v4";
const LEGACY_PERSIST_KEYS = ["tts.urls.v1", "tts.urls.v2", "tts.urls.v3"];
/** ElevenLabs Lily — primary hub kid voice (must match `KID_VOICE_ID` below). */
const LILY_VOICE_ID = "el:lily";
const BAD_OCLOCK_CACHE_SUFFIXES = ["||o clock", "||oh clock", "||oclock"];

/** el:lily @ 0.85, text exactly `o'clock` (ElevenLabs content hash). */
const OCLOCK_APOSTROPHE_HASH = "29278b6274ec960ca73d7f9532bad75a09ef5e5c5d";

function isLegacyBadTtsKey(key: string): boolean {
  return BAD_OCLOCK_CACHE_SUFFIXES.some((suffix) => key.endsWith(suffix));
}

function isValidOClockCacheEntry(key: string, url: string): boolean {
  if (!key.endsWith("||o'clock")) return true;
  // Only validate ElevenLabs Lily entries (legacy bad "o clock" workaround MP3s).
  if (!key.startsWith(`${LILY_VOICE_ID}|`)) return true;
  return url.includes(OCLOCK_APOSTROPHE_HASH);
}

function flushPersistMap(m: Map<string, string>) {
  try {
    const obj: Record<string, string> = {};
    for (const [k, v] of m.entries()) obj[k] = v;
    localStorage.setItem(PERSIST_KEY, JSON.stringify(obj));
  } catch { /* quota — ignore */ }
}

let persistMigrated = false;
function migrateLegacyTtsPersist() {
  if (persistMigrated || typeof window === "undefined") return;
  persistMigrated = true;
  try {
    const merged = new Map<string, string>();
    for (const legacyKey of LEGACY_PERSIST_KEYS) {
      const raw = localStorage.getItem(legacyKey);
      if (!raw) continue;
      try {
        const obj = JSON.parse(raw) as Record<string, string>;
        for (const [k, v] of Object.entries(obj)) {
          if (isLegacyBadTtsKey(k) || !isValidOClockCacheEntry(k, v)) continue;
          merged.set(k, v);
        }
      } catch { /* ignore */ }
      localStorage.removeItem(legacyKey);
    }
    const rawV4 = localStorage.getItem(PERSIST_KEY);
    if (rawV4) {
      try {
        const obj = JSON.parse(rawV4) as Record<string, string>;
        for (const [k, v] of Object.entries(obj)) merged.set(k, v);
      } catch { /* ignore */ }
    }
    for (const k of [...merged.keys()]) {
      const v = merged.get(k)!;
      if (isLegacyBadTtsKey(k) || !isValidOClockCacheEntry(k, v)) {
        merged.delete(k);
        audioCache.delete(k);
      }
    }
    persistMap = merged;
    flushPersistMap(merged);
  } catch { /* ignore */ }
}

const PERSIST_MAX = 500;
let persistMap: Map<string, string> | null = null;
const loadPersist = (): Map<string, string> => {
  migrateLegacyTtsPersist();
  if (persistMap) return persistMap;
  persistMap = new Map();
  try {
    const raw = localStorage.getItem(PERSIST_KEY);
    if (raw) {
      const obj = JSON.parse(raw) as Record<string, string>;
      for (const [k, v] of Object.entries(obj)) {
        if (isLegacyBadTtsKey(k) || !isValidOClockCacheEntry(k, v)) continue;
        persistMap.set(k, v);
      }
    }
  } catch { /* ignore */ }
  return persistMap;
};
const savePersist = (key: string, url: string) => {
  const m = loadPersist();
  if (m.has(key)) return;
  m.set(key, url);
  // Trim to PERSIST_MAX (FIFO).
  while (m.size > PERSIST_MAX) {
    const first = m.keys().next().value;
    if (!first) break;
    m.delete(first);
  }
  try {
    const obj: Record<string, string> = {};
    for (const [k, v] of m.entries()) obj[k] = v;
    localStorage.setItem(PERSIST_KEY, JSON.stringify(obj));
  } catch { /* quota — ignore */ }
};

async function sha256Hex(s: string): Promise<string> {
  const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(s));
  return Array.from(new Uint8Array(buf)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

// Mirror Edge Function voice/speed normalization so the hash matches.
const OPENAI_VOICES = new Set(["alloy", "shimmer", "nova", "echo", "onyx", "fable"]);
function normalizeForHash(voiceId: string, speed: number, accent: string | undefined) {
  const isEl = typeof voiceId === "string" && voiceId.startsWith("el:");
  let voice: string;
  const accentUpper = (accent || "").toUpperCase();
  if (isEl) {
    voice = voiceId; // ElevenLabs: keep as-is, accent doesn't apply
  } else {
    voice = OPENAI_VOICES.has(voiceId) ? voiceId : "alloy";
    if (accentUpper === "UK") voice = "fable";
    else if (accentUpper === "US") voice = "alloy";
  }
  // Allow slower speeds for young learners (down to 0.6).
  const safeSpeed = Math.min(1.2, Math.max(0.6, Number(speed) || 0.95));
  return { voice, safeSpeed, accentUpper };
}

async function predictCdnUrl(text: string, voiceId: string, speed: number, accent?: string): Promise<string> {
  const { voice, safeSpeed, accentUpper } = normalizeForHash(voiceId, speed, accent);
  // Strip dialogue speaker labels so the predicted hash matches what fetchTTS
  // sends (both clean identically). No-op for label-free text → hash unchanged.
  const safeText = cleanForTTS(String(text)).slice(0, 4000);
  // Hash key MUST mirror the edge function's `keyInput` exactly so the CDN
  // probe finds previously-synthesized audio.
  const provider = voice.startsWith("el:") ? "elevenlabs" : "openai";
  const keyInput = `${provider}|${voice}|${safeSpeed}|${accentUpper}|${safeText}`;
  const hash = await sha256Hex(keyInput);
  const path = `${hash.slice(0, 2)}/${hash}.mp3`;
  return buildCdnUrl(path);
}

async function probeCdn(url: string): Promise<boolean> {
  try {
    // Use GET with Range so the browser can cache the body for the real
    // playback fetch right after — HEAD doesn't populate the HTTP cache.
    const r = await fetch(url, { method: "GET", headers: { Range: "bytes=0-0" } });
    return r.ok || r.status === 206;
  } catch { return false; }
}

// Silently warm the audio cache for a phrase so that when the user later
// taps "play", the MP3 is already in memory and playback starts instantly.
// This does NOT touch any <audio> element, so it never triggers the iOS
// "now playing" indicator (Dynamic Island heart icon) — it's pure network.
export const prefetchTTS = (
  text: string,
  opts?: { accent?: "UK" | "US" | "BOTH"; voiceId?: string; speed?: number },
) => {
  const trimmed = (text || "").trim();
  if (!trimmed) return;
  const settings = loadSettings();
  const voiceId = opts?.voiceId ?? settings.voiceId;
  const speed = opts?.speed ?? settings.speed;
  const accent = opts?.accent;
  const cacheKey = `${voiceId}|${speed}|${accent || ''}|${trimmed}`;
  if (audioCache.has(cacheKey)) return;
  // 1) localStorage hit → reuse known-good CDN URL across sessions.
  const persisted = loadPersist().get(cacheKey);
  if (persisted && !isLegacyBadTtsKey(cacheKey) && isValidOClockCacheEntry(cacheKey, persisted)) {
    audioCache.set(cacheKey, persisted);
    return;
  }
  // 2) Try predictive CDN probe first (no Edge Function round-trip).
  void (async () => {
    try {
      const guess = await predictCdnUrl(trimmed, voiceId, speed, accent);
      if (await probeCdn(guess)) {
        audioCache.set(cacheKey, guess);
        savePersist(cacheKey, guess);
        return;
      }
    } catch { /* fall through */ }
    // 3) Cold — invoke Edge Function which will synthesize + persist.
    void fetchTTS(trimmed, voiceId, speed, accent);
  })();
};

// Batch-prefetch a list of phrases (e.g. an entire review queue). Runs
// in parallel but stays bounded so we don't open 50 sockets at once.
export const prefetchTTSBatch = (texts: string[], opts?: { accent?: "UK" | "US" | "BOTH" }) => {
  const seen = new Set<string>();
  for (const t of texts) {
    const trimmed = (t || "").trim();
    if (!trimmed || seen.has(trimmed)) continue;
    seen.add(trimmed);
    prefetchTTS(trimmed, opts);
  }
};

